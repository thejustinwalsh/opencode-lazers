#!/usr/bin/env python3
"""Reproducible asset prep. Run: python3 -I website/scripts/prepare-assets.py (needs Pillow, numpy).
Inputs: website/design/cat.png, marks.png. Outputs: website/src/assets/*.png + cat-geometry.ts
Does not embed provenance; run the impeccable embed-prompt step afterwards (see assets README step in report)."""
import json, pathlib
import numpy as np
from PIL import Image
from scipy import ndimage as ndi

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "assets"
OUT.mkdir(parents=True, exist_ok=True)


def hexrgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i : i + 2], 16) for i in (0, 2, 4))


INK, PERI, PERI_MID = hexrgb("13095E"), hexrgb("A3A5F9"), hexrgb("5855A7")
MAG, MAG_DEEP, CYAN, EYE_MAG = hexrgb("F81497"), hexrgb("C2006A"), hexrgb("19EBF1"), hexrgb("FF3FD6")
IVORY = hexrgb("F5F4FA")


def quantize(rgb, anchors):
    """anchors: list of (src_rgb, dst_rgb). Returns dst colours by nearest src, plus index."""
    src = np.array([s for s, _ in anchors], float)
    dst = np.array([d for _, d in anchors], np.uint8)
    d = ((rgb[:, :, None, :].astype(float) - src[None, None]) ** 2).sum(-1)
    idx = d.argmin(-1)
    return dst[idx], idx


def to_png8(rgb, alpha_mask, path):
    h, w, _ = rgb.shape
    flat = np.zeros((h, w, 4), np.uint8)
    flat[..., :3] = rgb
    flat[..., 3] = np.where(alpha_mask, 255, 0)
    colors = sorted({tuple(c) for c in rgb[alpha_mask]})
    pal = [(0, 0, 0)] + colors  # index 0 transparent
    lut = {c: i + 1 for i, c in enumerate(colors)}
    idx = np.zeros((h, w), np.uint8)
    ys, xs = np.nonzero(alpha_mask)
    for y, x in zip(ys, xs):
        idx[y, x] = lut[tuple(rgb[y, x])]
    im = Image.fromarray(idx, "P")
    flatpal = [v for c in pal for v in c]
    im.putpalette(flatpal + [0] * (768 - len(flatpal)))
    im.save(path, optimize=True, transparency=0)


# ---------- cat ----------
cat = np.array(Image.open(ROOT / "design/cat.png").convert("RGBA"))
op = cat[..., 3] >= 128
lab, n = ndi.label(op)
sizes = ndi.sum(op, lab, range(1, n + 1))
op = lab == (1 + int(np.argmax(sizes)))  # drop ghost fragments
op = ndi.binary_fill_holes(op) | op
ys, xs = np.nonzero(op)
y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
cat, op = cat[y0:y1, x0:x1], op[y0:y1, x0:x1]
rgb = cat[..., :3]
anchors = [
    ((252, 234, 204), IVORY), ((250, 232, 216), IVORY), ((250, 250, 216), IVORY), ((232, 216, 200), IVORY),
    ((248, 248, 232), IVORY),
    ((8, 8, 104), INK), ((8, 8, 88), INK), ((8, 8, 136), INK), ((8, 8, 120), INK), ((24, 24, 120), INK),
    ((152, 152, 248), PERI), ((136, 136, 248), PERI), ((136, 152, 248), PERI), ((168, 168, 248), PERI),
    ((248, 72, 40), MAG), ((248, 56, 40), MAG),
    ((168, 24, 72), MAG_DEEP), ((184, 24, 72), MAG_DEEP),
    ((8, 248, 248), CYAN), ((248, 8, 200), EYE_MAG),
]
out, idx = quantize(rgb, anchors)
h, w = op.shape
to_png8(out, op, OUT / "cat.png")

# eyes: centroid of the pixels that mapped to the eye anchors
cy_i, em_i = len(anchors) - 2, len(anchors) - 1


def centroid(i):
    m = (idx == i) & op
    yy, xx = np.nonzero(m)
    return [round(float((xx.mean() + 0.5) / w), 4), round(float((yy.mean() + 0.5) / h), 4)]


cyan_eye, mag_eye = centroid(cy_i), centroid(em_i)
rows = 64
contour = []
for r in range(rows):
    band = op[int(r * h / rows) : int((r + 1) * h / rows)]
    cols = np.nonzero(band.any(0))[0]
    contour.append([round(float(cols.min() / w), 4), round(float((cols.max() + 1) / w), 4)] if len(cols) else None)
ts = f"""// Generated by scripts/prepare-assets.py. Do not edit.
export const CAT_SIZE = {{ width: {w}, height: {h} }} as const
/** Pupil centroids, normalized 0-1 against the sprite width and height. */
export const CAT_CYAN_EYE = {json.dumps(cyan_eye)} as const
export const CAT_MAGENTA_EYE = {json.dumps(mag_eye)} as const
/** Per band row: [minX, maxX] of opaque pixels, normalized; null when the band is empty. */
export const CAT_CONTOUR: readonly (readonly [number, number] | null)[] = {json.dumps(contour)}
"""
(OUT / "cat-geometry.ts").write_text(ts)
print("cat", w, h, "cyan", cyan_eye, "magenta", mag_eye)

# ---------- marks ----------
mraw = np.array(Image.open(ROOT / "design/marks.png").convert("RGBA"))
m = mraw[..., :3].astype(int)
H, W, _ = m.shape
art = mraw[..., 3] >= 160  # drops the faint ghost artifacts in the transparent field
manchors = [
    ((21, 15, 120), INK), ((80, 90, 225), PERI_MID), ((135, 150, 250), PERI), ((250, 35, 150), MAG),
    ((20, 20, 110), INK),
]
quads = {
    "flag": (0, 0, W // 2, H // 2),
    "corner": (W // 2, 0, W, H // 2),
    "sparkle": (0, H // 2, W // 2, H),
    "stripes": (W // 2, H // 2, W, H),
}
TARGET_W = {"flag": 200, "corner": 200, "sparkle": 120, "stripes": 200}
for name, (a, b, c, d) in quads.items():
    q = m[b:d, a:c]
    mask = art[b:d, a:c]
    mask = ndi.binary_opening(mask, iterations=1) if name != "sparkle" else mask
    lab, n = ndi.label(mask, structure=np.ones((3, 3)))
    if n:
        sz = ndi.sum(mask, lab, range(1, n + 1))
        keep = [i + 1 for i, s in enumerate(sz) if s >= 60]
        mask = np.isin(lab, keep)
    ys, xs = np.nonzero(mask)
    q, mask = q[ys.min() : ys.max() + 1, xs.min() : xs.max() + 1], mask[ys.min() : ys.max() + 1, xs.min() : xs.max() + 1]
    # box downscale to a small native-ish grid, then re-quantize so edges stay hard
    scale = TARGET_W[name] / q.shape[1]
    nw, nh = TARGET_W[name], max(1, round(q.shape[0] * scale))
    rgbim = Image.fromarray(np.where(mask[..., None], q, 0).astype(np.uint8)).resize((nw, nh), Image.BOX)
    mk = Image.fromarray((mask * 255).astype(np.uint8)).resize((nw, nh), Image.BOX)
    mk = np.array(mk) >= 128
    # unpremultiply colour against white bleed: re-run nearest-anchor
    out, _ = quantize(np.array(rgbim), manchors)
    to_png8(out, mk, OUT / f"mark-{name}.png")
    print(name, nw, nh)
